const assert=require('node:assert/strict'),path=require('node:path');
module.exports=async(page,context,base,artifacts,violations)=>{
 const uploads=[],watch=r=>{if(['POST','PUT','PATCH'].includes(r.method()))uploads.push(r.url());};page.on('request',watch);
 await page.goto(`${base}index.html?tab=liturgy&date=2026-11-12&rite=roman`);
 await page.locator('[data-act="liturgyview"][data-v="mass"]').click();
 await page.locator('.reader-offline > summary').click();
 await page.locator('#liturgical-file').setInputFiles({name:'private-missal.epub',mimeType:'application/epub+zip',buffer:require('./epub-reader-browser.cjs').epub(false,true)});
 await page.waitForFunction(()=>document.querySelector('.reader-inline-text')?.textContent.includes('Fixture collect'));
 await page.locator('.reader-offline > summary').click();
 assert.equal(await page.locator('.reader-inline-text').isVisible(),true,'text stays directly on the page when file management is closed');
 assert.equal(await page.locator('dialog[open]').count(),0,'no separate viewer opens');
 assert.match(await page.locator('.reader-edition').innerText(),/between popes/);
 assert.match(await page.locator('.reader-match').innerText(),/Matching prayers for Saint Josaphat/);
 await page.locator('.reader-book-links button').click();
 await page.waitForFunction(()=>document.querySelector('.reader-inline-text')?.textContent.includes('Fixture fixed Mass responses'));
 await page.locator('.reader-missal-shortcuts button').filter({hasText:'Day’s prayers'}).click();
 await page.waitForFunction(()=>document.querySelector('.reader-inline-text')?.textContent.includes('Fixture collect'));
 await page.locator('#inline-book-search').fill('responses');
 assert.equal(await page.locator('#inline-book-section option').count(),1);
 await page.selectOption('#inline-book-section','3');
 await page.waitForFunction(()=>document.querySelector('.reader-inline-text')?.textContent.includes('Fixture fixed Mass responses'));
 await page.goto(`${base}index.html?tab=liturgy&date=2026-11-15&rite=roman`);
 await page.waitForFunction(()=>document.querySelector('.reader-inline-text')?.textContent.includes('Fixture Sunday prayer'));
 await page.addScriptTag({path:require.resolve('axe-core/axe.min.js')});
 const audit=await page.evaluate(()=>axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa']}}));
 violations.push(...audit.violations.map(v=>({tab:'inline-private-missal',id:v.id,examples:v.nodes.map(n=>({html:n.html,summary:n.failureSummary}))})));
 await page.screenshot({path:path.join(artifacts,'inline-private-missal.png'),fullPage:true});
 await context.setOffline(true);await page.reload();
 await page.waitForFunction(()=>document.querySelector('.reader-inline-text')?.textContent.includes('Fixture Sunday prayer'));
 assert.equal(await page.locator('dialog[open]').count(),0);await context.setOffline(false);
 await page.goto(`${base}index.html?tab=liturgy&date=2026-11-13&rite=roman`);
 await page.waitForFunction(()=>document.querySelector('.reader-match')?.textContent.includes('No unique automatic match'));
 assert.deepEqual(uploads,[],'private Missal text is never uploaded');page.off('request',watch);
 console.log('Inline Roman Missal: date match, full inline text, internal links, search, edition note, unmatched dates and offline reopening passed.');
};
